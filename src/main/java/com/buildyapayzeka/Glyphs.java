package com.buildyapayzeka;

import java.text.Normalizer;
import java.util.*;

/** Bloklarla yazı yazmak için 5 satır yüksekliğinde piksel font. '#' = blok. */
final class Glyphs {
    private static final Map<Character, String[]> F = new HashMap<>();

    private static void g(char c, String... rows) { F.put(c, rows); }

    static {
        g('A', ".###.", "#...#", "#####", "#...#", "#...#");
        g('B', "####.", "#...#", "####.", "#...#", "####.");
        g('C', ".####", "#....", "#....", "#....", ".####");
        g('D', "####.", "#...#", "#...#", "#...#", "####.");
        g('E', "#####", "#....", "###..", "#....", "#####");
        g('F', "#####", "#....", "###..", "#....", "#....");
        g('G', ".####", "#....", "#..##", "#...#", ".###.");
        g('H', "#...#", "#...#", "#####", "#...#", "#...#");
        g('I', "###", ".#.", ".#.", ".#.", "###");
        g('J', "..###", "...#.", "...#.", "#..#.", ".##..");
        g('K', "#...#", "#..#.", "###..", "#..#.", "#...#");
        g('L', "#....", "#....", "#....", "#....", "#####");
        g('M', "#...#", "##.##", "#.#.#", "#...#", "#...#");
        g('N', "#...#", "##..#", "#.#.#", "#..##", "#...#");
        g('O', ".###.", "#...#", "#...#", "#...#", ".###.");
        g('P', "####.", "#...#", "####.", "#....", "#....");
        g('Q', ".###.", "#...#", "#.#.#", "#..#.", ".##.#");
        g('R', "####.", "#...#", "####.", "#..#.", "#...#");
        g('S', ".####", "#....", ".###.", "....#", "####.");
        g('T', "#####", "..#..", "..#..", "..#..", "..#..");
        g('U', "#...#", "#...#", "#...#", "#...#", ".###.");
        g('V', "#...#", "#...#", "#...#", ".#.#.", "..#..");
        g('W', "#...#", "#...#", "#.#.#", "##.##", "#...#");
        g('X', "#...#", ".#.#.", "..#..", ".#.#.", "#...#");
        g('Y', "#...#", ".#.#.", "..#..", "..#..", "..#..");
        g('Z', "#####", "...#.", "..#..", ".#...", "#####");
        g('0', ".###.", "#..##", "#.#.#", "##..#", ".###.");
        g('1', ".#.", "##.", ".#.", ".#.", "###");
        g('2', ".###.", "#...#", "..##.", ".#...", "#####");
        g('3', "####.", "....#", ".###.", "....#", "####.");
        g('4', "#..#.", "#..#.", "#####", "...#.", "...#.");
        g('5', "#####", "#....", "####.", "....#", "####.");
        g('6', ".###.", "#....", "####.", "#...#", ".###.");
        g('7', "#####", "...#.", "..#..", ".#...", ".#...");
        g('8', ".###.", "#...#", ".###.", "#...#", ".###.");
        g('9', ".###.", "#...#", ".####", "....#", ".###.");
        g(' ', "..", "..", "..", "..", "..");
        g('-', "...", "...", "###", "...", "...");
        g('.', ".", ".", ".", ".", "#");
        g('!', "#", "#", "#", ".", "#");
        g(':', ".", "#", ".", "#", ".");
        g('/', "..#", "..#", ".#.", "#..", "#..");
        g('+', "...", ".#.", "###", ".#.", "...");
    }

    /** Türkçe harfleri sadeleştirip büyük harfe çevirir. */
    static String clean(String s) {
        String u = s.replace('İ', 'I').replace('ı', 'I').toUpperCase(Locale.ROOT);
        u = Normalizer.normalize(u, Normalizer.Form.NFD).replaceAll("\\p{M}+", "");
        StringBuilder b = new StringBuilder();
        for (char c : u.toCharArray()) b.append(F.containsKey(c) ? c : ' ');
        return b.toString();
    }

    /** Verilen yazının piksel haritası: [satır 0=üst][sütun] */
    static boolean[][] render(String text) {
        String t = clean(text);
        int w = 0;
        for (char c : t.toCharArray()) w += F.get(c)[0].length() + 1;
        w = Math.max(0, w - 1);
        boolean[][] out = new boolean[5][w];
        int x = 0;
        for (char c : t.toCharArray()) {
            String[] rows = F.get(c);
            for (int r = 0; r < 5; r++)
                for (int k = 0; k < rows[r].length(); k++) out[r][x + k] = rows[r].charAt(k) == '#';
            x += rows[0].length() + 1;
        }
        return out;
    }
}
